-- Presence: when the backend last heard from the device, and what the device last reported about itself.
-- A device is never considered online just because a row exists (see DeviceService.connectionOf).
ALTER TABLE devices ADD COLUMN last_seen_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE devices ADD COLUMN reported_state VARCHAR(10);

-- "UNCONNECTED" described connectivity, which is now tracked separately; status is only the lifecycle.
UPDATE devices SET status = 'ACTIVE' WHERE status = 'UNCONNECTED';

-- One row per accepted telemetry message. Any reading may be NULL (that sensor failed or is absent).
CREATE TABLE telemetry_readings (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_uuid      UUID                     NOT NULL REFERENCES devices (id) ON DELETE CASCADE,
    received_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    device_timestamp TIMESTAMP WITH TIME ZONE,
    seq              BIGINT                   NOT NULL,
    temperature_c    DOUBLE PRECISION,
    humidity_pct     DOUBLE PRECISION,
    motion           BOOLEAN,
    -- Raw MQ-2 ADC reading. Deliberately NOT converted to ppm: that needs calibration we don't have.
    gas_raw          INTEGER,
    -- SHA-256 of the raw payload, used to drop QoS 1 redeliveries.
    dedupe_key       VARCHAR(64)              NOT NULL
);

CREATE INDEX idx_telemetry_device_received ON telemetry_readings (device_uuid, received_at);
CREATE INDEX idx_telemetry_dedupe ON telemetry_readings (device_uuid, dedupe_key);
