-- Historical data for the ML pipeline. Nothing here is invented: every row records something that really happened.

-- Device connectivity history. One row per change (ONLINE <-> OFFLINE), so outages can be counted and dated later.
-- The devices table only keeps the latest state; this keeps all of them.
CREATE TABLE device_status_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_uuid  UUID                     NOT NULL REFERENCES devices (id) ON DELETE CASCADE,
    -- ONLINE | OFFLINE
    state        VARCHAR(10)              NOT NULL,
    -- why: "reported online", "reported offline (last will)", "silent" ...
    reason       VARCHAR(60)              NOT NULL,
    changed_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    -- when the backend last heard from the device at that moment (null if never)
    last_seen_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_device_status_events_device ON device_status_events (device_uuid, changed_at);

-- Every training run (manual or automatic), kept as history. ml_models still holds the current model; a run that
-- produced a model gets the next version number.
CREATE TABLE ml_training_runs (
    id               UUID                     PRIMARY KEY,
    device_uuid      UUID                     NOT NULL REFERENCES devices (id) ON DELETE CASCADE,
    model_type       VARCHAR(20)              NOT NULL,
    -- the model version this run produced; null when it produced none (insufficient data)
    version          INTEGER,
    -- MANUAL | AUTO
    trigger_kind     VARCHAR(10)              NOT NULL,
    -- READY | LOW_QUALITY | INSUFFICIENT_DATA
    status           VARCHAR(20)              NOT NULL,
    reason           VARCHAR(400),
    -- true when this run's model became the current one
    became_current   BOOLEAN                  NOT NULL,
    time_zone        VARCHAR(50)              NOT NULL,
    feature_set      VARCHAR(120)             NOT NULL,
    trained_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    duration_ms      BIGINT                   NOT NULL,
    data_from        TIMESTAMP WITH TIME ZONE,
    data_to          TIMESTAMP WITH TIME ZONE,
    samples          INTEGER                  NOT NULL,
    labeled_buckets  INTEGER                  NOT NULL,
    positive_buckets INTEGER                  NOT NULL,
    distinct_days    INTEGER                  NOT NULL,
    metrics_json     VARCHAR(2000)
);

CREATE INDEX idx_ml_training_runs_device ON ml_training_runs (device_uuid, model_type, trained_at);

-- Current model version per device (0 = no model yet). Existing trained models count as version 1.
ALTER TABLE ml_models ADD COLUMN version INTEGER NOT NULL DEFAULT 0;
UPDATE ml_models SET version = 1 WHERE model_json IS NOT NULL;
