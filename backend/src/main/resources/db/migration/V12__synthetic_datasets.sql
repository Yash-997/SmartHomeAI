-- SYNTHETIC training data, kept completely apart from real device telemetry.
-- Nothing here is ever written to telemetry_readings, and nothing that reads real data (dashboard, security, anomaly
-- scans, automation, assistant) reads these tables.

-- One generated dataset per device and generation settings. The unique key makes generation idempotent: asking again
-- with the same settings returns the existing dataset instead of creating duplicates.
CREATE TABLE synthetic_datasets (
    id                UUID                     PRIMARY KEY,
    device_uuid       UUID                     NOT NULL REFERENCES devices (id) ON DELETE CASCADE,
    created_by        UUID                     NOT NULL,
    generator_version VARCHAR(20)              NOT NULL,
    seed              BIGINT                   NOT NULL,
    days              INTEGER                  NOT NULL,
    time_zone         VARCHAR(50)              NOT NULL,
    starts_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    record_count      INTEGER                  NOT NULL,
    offline_minutes   INTEGER                  NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    -- JSON: the labelled anomaly scenarios (kind, window) and how the existing detectors did on them (null until evaluated)
    scenarios_json    VARCHAR(4000)            NOT NULL,
    evaluation_json   VARCHAR(8000),
    CONSTRAINT uq_synthetic_dataset UNIQUE (device_uuid, generator_version, seed, days)
);

-- One generated reading per minute while the simulated device is online. Labels (occupied, scenario) are ground truth
-- that real telemetry never has.
CREATE TABLE synthetic_readings (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id    UUID                     NOT NULL REFERENCES synthetic_datasets (id) ON DELETE CASCADE,
    recorded_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    temperature_c DOUBLE PRECISION,
    humidity_pct  DOUBLE PRECISION,
    motion        BOOLEAN,
    gas_raw       INTEGER,
    -- OCCUPIED | UNOCCUPIED
    occupancy     VARCHAR(10)              NOT NULL,
    -- NORMAL, or the labelled anomaly scenario this minute belongs to
    scenario      VARCHAR(20)              NOT NULL,
    CONSTRAINT uq_synthetic_reading UNIQUE (dataset_id, recorded_at)
);

CREATE INDEX idx_synthetic_readings_dataset ON synthetic_readings (dataset_id, recorded_at);

-- Simulated connectivity changes (random outages and the labelled disconnection scenario).
CREATE TABLE synthetic_connectivity_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id  UUID                     NOT NULL REFERENCES synthetic_datasets (id) ON DELETE CASCADE,
    changed_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    state       VARCHAR(10)              NOT NULL,
    reason      VARCHAR(60)              NOT NULL
);

-- Training history says where its data came from. Every existing run was trained on real telemetry.
ALTER TABLE ml_training_runs ADD COLUMN data_source VARCHAR(10) NOT NULL DEFAULT 'REAL';
ALTER TABLE ml_training_runs ADD COLUMN dataset_id UUID;
