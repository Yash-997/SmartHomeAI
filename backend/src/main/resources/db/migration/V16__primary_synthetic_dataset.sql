-- One shared SYNTHETIC dataset drives predictive occupancy: training, evaluation, analytics and the demonstration.
-- It belongs to no physical device (device_uuid is null; device_identifier names the simulated one). Every row in the
-- synthetic_* tables is synthetic by construction, and the dataset row also says so explicitly.
ALTER TABLE synthetic_datasets ALTER COLUMN device_uuid DROP NOT NULL;
ALTER TABLE synthetic_datasets ADD COLUMN data_source VARCHAR(10) NOT NULL DEFAULT 'SYNTHETIC';
ALTER TABLE synthetic_datasets ADD COLUMN device_identifier VARCHAR(40);
ALTER TABLE synthetic_datasets ADD COLUMN is_primary BOOLEAN NOT NULL DEFAULT FALSE;

-- Ground-truth resident departures and arrivals.
CREATE TABLE synthetic_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id  UUID                     NOT NULL REFERENCES synthetic_datasets (id) ON DELETE CASCADE,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    kind        VARCHAR(10)              NOT NULL
);

CREATE INDEX idx_synthetic_events_dataset ON synthetic_events (dataset_id, occurred_at);

-- The trained predictive model, saved so that inference loads it instead of training. Only the newest version is kept.
CREATE TABLE predictive_models (
    version       INTEGER                  NOT NULL PRIMARY KEY,
    dataset_id    UUID                     NOT NULL REFERENCES synthetic_datasets (id) ON DELETE CASCADE,
    trained_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    training_rows INTEGER                  NOT NULL,
    model_json    TEXT                     NOT NULL
);
