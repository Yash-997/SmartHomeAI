package com.smarthome.ml;

import java.time.Instant;
import java.util.List;
import java.util.Map;
import java.util.UUID;

import com.smarthome.ml.MlDtos.MetricsResponse;
import com.smarthome.ml.MlDtos.PredictionResponse;

/** API shapes for the SYNTHETIC dataset and its demonstration model. Every response says source = SYNTHETIC. */
public final class SyntheticDtos {

	private SyntheticDtos() {
	}

	public static final String SOURCE = "SYNTHETIC";
	public static final String NOTICE = "SYNTHETIC DATA: generated by SmartHomeAI to exercise the ML pipeline. It is not your home's history, "
			+ "and the demonstration model trained on it has not learned your routine. Your device's real predictions are shown separately and "
			+ "only ever use real telemetry.";

	public record ScenarioInfo(String scenario, String description, Instant from, Instant to) {
	}

	public record DatasetInfo(UUID id, String generatorVersion, long seed, int days, String timeZone, Instant startsAt, Instant endsAt,
			int recordCount, int offlineMinutes, int connectivityEvents, double occupiedShare, double motionShare, Instant createdAt,
			List<ScenarioInfo> scenarios) {
	}

	/** How the data was split and how the occupancy forecast agrees with the generator's true occupancy. */
	public record TrainingDetails(double lambda, Map<String, Double> validationLogLoss, SyntheticTrainer.Split train,
			SyntheticTrainer.Split validation, SyntheticTrainer.Split test, long embargoMinutes, int embargoDropped, int scenarioSlotsExcluded,
			SyntheticTrainer.OccupancyAgreement agreementWithTrueOccupancy) {
	}

	public record StoredEvaluation(TrainingDetails training, SyntheticAnomalyEvaluator.Evaluation anomalies) {
	}

	public record ModelInfo(String state, int version, Instant trainedAt, String timeZone, String message, MetricsResponse metrics) {
	}

	public record SyntheticStatusResponse(String source, String notice, DatasetInfo dataset, ModelInfo model, TrainingDetails training,
			SyntheticAnomalyEvaluator.Evaluation anomalies, boolean generated) {
	}

	public record SyntheticForecastResponse(String source, String notice, int modelVersion, String timeZone, List<PredictionResponse> points) {
	}
}
